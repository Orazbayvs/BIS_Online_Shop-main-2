def load_local_env_file(path):
    """Load simple NAME=value lines from configdrf/.env (git-ignored).

    Real environment variables always win, so CI and production are unaffected.
    This only saves typing ``export ...`` before every local command.
    """
    try:
        lines = Path(path).read_text(encoding='utf-8').splitlines()
    except (FileNotFoundError, OSError, UnicodeDecodeError):
        return
    for raw_line in lines:
        line = raw_line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        if line.startswith('export '):
            line = line[len('export '):].strip()
        name, value = line.split('=', 1)
        name, value = name.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
            value = value[1:-1]
        if name:
            os.environ.setdefault(name, value)


load_local_env_file(BASE_DIR / '.env')


