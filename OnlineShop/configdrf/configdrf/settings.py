# PostgreSQL is the project database. Without DATABASE_URL, Django connects to a
# local PostgreSQL server using POSTGRES_* variables (defaults: database
# "onlineshop", the current OS user, no password, localhost:5432) - this matches
# a Homebrew / Postgres.app installation. A full URL can be given instead:
# postgresql://onlineshop:password@db.example:5432/onlineshop?sslmode=require
# SQLite remains available only on request: DATABASE_URL=sqlite:///path/to/db.sqlite3
# The URL is deliberately never logged so database credentials stay private.

LOCAL_DATABASE_HOSTS = ('localhost', '127.0.0.1', '::1')


def default_ssl_mode(host):
    if host in LOCAL_DATABASE_HOSTS:
        return os.environ.get('DJANGO_DB_SSLMODE', 'prefer')
    return os.environ.get('DJANGO_DB_SSLMODE', 'require' if not DEBUG else 'prefer')


def local_os_user():
    try:
        return getpass.getuser()
    except Exception:  # noqa: BLE001 - some containers have no passwd entry
        return 'postgres'


def postgresql_settings(name, user, password, host, port, sslmode):
    return {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': name,
            'USER': user,
            'PASSWORD': password,
            'HOST': host,
            'PORT': str(port),
            'CONN_MAX_AGE': int(os.environ.get('DJANGO_DB_CONN_MAX_AGE', '60')),
            'CONN_HEALTH_CHECKS': True,
            'OPTIONS': {'sslmode': sslmode},
        }
    }


def database_settings():
    database_url = os.environ.get('DATABASE_URL', '').strip()
    if not database_url:
        host = os.environ.get('POSTGRES_HOST', 'localhost')
        return postgresql_settings(
            name=os.environ.get('POSTGRES_DB', 'onlineshop'),
            user=os.environ.get('POSTGRES_USER') or local_os_user(),
            password=os.environ.get('POSTGRES_PASSWORD', ''),
            host=host,
            port=os.environ.get('POSTGRES_PORT', '5432'),
            sslmode=default_ssl_mode(host),
        )

    parsed = urlparse(database_url)
    scheme = parsed.scheme.lower()
    if scheme in ('postgres', 'postgresql'):
        database_name = unquote(parsed.path.lstrip('/'))
        if not database_name or not parsed.hostname:
            raise RuntimeError('DATABASE_URL must include a PostgreSQL host and database name.')
        try:
            port = parsed.port
        except ValueError as exc:
            raise RuntimeError('DATABASE_URL contains an invalid PostgreSQL port.') from exc

        query = parse_qs(parsed.query)
        sslmode = query.get('sslmode', [default_ssl_mode(parsed.hostname)])[0]
        return postgresql_settings(
            name=database_name,
            user=unquote(parsed.username or ''),
            password=unquote(parsed.password or ''),
            host=parsed.hostname,
            port=port or 5432,
            sslmode=sslmode,
        )

    if scheme == 'sqlite':
        database_name = unquote(parsed.path)
        if not database_name:
            raise RuntimeError('SQLite DATABASE_URL must include a database path.')
        return {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': database_name,
            }
        }

    raise RuntimeError('DATABASE_URL must use postgresql://, postgres://, or sqlite://.')


DATABASES = database_settings()


